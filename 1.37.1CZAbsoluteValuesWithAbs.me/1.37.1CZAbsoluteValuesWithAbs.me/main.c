#include<stdio.h>
#include<math.h>



int main()
{

	//This just uses "sqrt" function to get square root of a number (both whole and decimal)
	//Here: 12.806248. Remember that "%f" default puts out 6 decimal places.
	printf("%f \n", sqrt(164)); 

	//This is another useful function. "power" just take the power of two numbers.
	//The second number is what the first number is being raised to.
	printf("%f \n", pow(13, 2));

}